def _item(h: str, t: str) -> dict:
    return {'h': h, 't': t}


def _x(st: Station, x: float) -> int:
    return round(x - min(n.x for n in st.g.nodes.values()))


def _sides(st: Station, edge: int, t: float) -> list[str]:
    """Участки по обе стороны стыка."""
    out = []
    for s in st.sections:
        for p in s['pieces']:
            if p['edge'] == edge and (abs(p['t0'] - t) < 0.05 or abs(p['t1'] - t) < 0.05):
                out.append(s['name'] or 'участок')
                break
    return out


def joint(st: Station, i: int) -> dict:
    j = st.joints[i]
    title, text, ref = JOINT_RULES.get(j.rule, ('Изолирующий стык', '', ''))
    x, _ = st.g.point_on(st.g.edges[j.edge], j.t)
    items = [_item('Правило', text)]
    if j.why:
        items.append(_item('Здесь', j.why[0].upper() + j.why[1:] + '.'))
    sides = _sides(st, j.edge, j.t)
    if len(sides) == 2:
        items.append(_item('Разделяет', f'{sides[0]} и {sides[1]}'))
    if j.negab:
        items.append(_item('Негабаритный', NEGAB[0]))
        ref = f'{ref}; {NEGAB[1]}' if ref else NEGAB[1]
    items.append(_item('Ордината', f'{_x(st, x)} мм от левого края'))
    return {'title': f'Стык «{j.rule}» – {title.lower()}' if j.rule != 'р' else title,
            'items': items, 'ref': ref}


def signal(st: Station, i: int) -> dict:
    s = st.signals[i]
    title, text, ref = SIGNAL_KINDS.get(s.kind, ('Светофор', '', 'п. 2.5'))
    x, _ = st.g.point_on(st.g.edges[s.joint.edge], s.joint.t)
    throat = throat_of(st, x)
    items = [_item('Назначение', text)]
    if s.why:
        items.append(_item('Здесь', s.why[0].upper() + s.why[1:] + '.'))
    if s.kind.startswith('exit'):
        items.append(_item('Имя', f'{s.name}: {throat}, отсюда отправляются '
                           f'{"нечётные" if s.name.startswith("Н") else "чётные"} поезда.'))
    elif s.kind.startswith('man'):
        items.append(_item('Имя', f'{s.name}: {throat} – '
                           f'{"нечётные" if st.odd_side(x) else "чётные"} номера.'))
    if getattr(s, 'manual', False):
        items.append(_item('Правка', 'Светофор изменён или добавлен вручную.'))
    items.append(_item('Стоит', f'у стыка «{s.joint.rule}», ордината {_x(st, x)} мм, '
                       'справа по ходу движения (рис. 2.13)'))
    return {'title': f'{s.name} – {title.lower()}', 'items': items, 'ref': ref}


def section(st: Station, name: str) -> dict:
    s = next((s for s in st.sections if s['name'] == name), None)
    if s is None:
        raise ValueError(f'участка {name} нет')
    sw = sorted((_nm(st, n) for n in s['switches']), key=lambda v: (len(v), v))
    items = []
    if sw:
        items.append(_item('Имя', 'Стрелочный участок называют по номерам входящих в него '
                           f'стрелок с буквами СП: стрелки {", ".join(sw)}.'))
        items.append(_item('Стрелок', f'{len(sw)} из 3 допустимых' + (
            ' – больше нормы, нужен ещё стык (п. 2.4 и)' if len(sw) > 3 else '')))
    elif name.endswith('П') and name[:-1] in set(st.track_names.values()):
        items.append(_item('Имя', f'Путь {name[:-1]} станции – отдельный участок {name} (п. 2.4 б).'))
    else:
        items.append(_item('Имя', 'Бесстрелочный участок – по пути или по соседним стрелкам.'))
    items.append(_item('Зачем', 'Участок – это рельсовая цепь: по ней контролируется, '
                       'свободен ли путь или стрелка. Границы – изолирующие стыки.'))
    return {'title': f'Участок {name}', 'items': items, 'ref': 'п. 2.4, рис. 2.7–2.8'}


def node(st: Station, nid: int) -> dict:
    g = st.g
    n = g.nodes[nid]
    throat = throat_of(st, n.x)
    if nid in st.sw:
        sec = next((s['name'] for s in st.sections if nid in s['switches']), '')
        return {'title': f'Стрелка {_nm(st, nid)}',
                'items': [_item('Номер', f'{throat.capitalize()}: '
                                f'{"нечётные" if st.odd_side(n.x) else "чётные"} номера, '
                                'по порядку от входного светофора к оси станции; стрелки '
                                'съездов и стрелочных улиц – подряд.'),
                          _item('Участок', sec or '–'),
                          _item('Ордината', f'{_x(st, n.x)} мм от левого края')],
                'ref': 'п. 2.3, рис. 2.4–2.5'}
    title, text, ref = ENDS.get(n.mark or '', ('Конец пути', '', ''))
    items = [_item('Что это', text)] if text else []
    if n.label:
        items.append(_item('Имя', n.label))
    if n.fixed_mark:
        items.append(_item('Правка', 'Тип конца задан вручную.'))
    return {'title': title, 'items': items, 'ref': ref}
